import AppKit

/// Ein Eintrag im Verlauf der Zwischenablage: Text, ein Bild oder Dateien.
struct Clip: Identifiable, Equatable {
    enum Kind: Equatable {
        case text
        case image(Data)            // PNG-Daten
        case files([URL])
    }
    let id = UUID()
    var text: String                // bei Bildern und Dateien die Beschreibung („Bild 1200 × 800", Dateinamen)
    var date: Date
    var app: String
    var kind: Kind = .text

    var thumbnail: NSImage? {
        if case .image(let data) = kind { return NSImage(data: data) }
        return nil
    }
}

/// Verlauf der Zwischenablage: merkt sich, was du zuletzt kopiert hast, damit du es erneut einfügen kannst.
/// Alles liegt nur im Arbeitsspeicher – nach dem Beenden von Lotse ist der Verlauf weg, nichts landet auf der Platte.
/// Kennwörter aus Passwort-Managern (als „vertraulich" markiert) werden nicht aufgenommen.
final class ClipboardSource {
    private let model: IslandModel
    private var timer: Timer?
    private var count = NSPasteboard.general.changeCount
    private static let secret: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                              "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
    static let limit = 40
    static let imageLimit = 8           // Bilder sind groß – nur die letzten bleiben

    init(model: IslandModel) { self.model = model }

    func start() {
        model.copyClip = { [weak self] clip in self?.copy(clip) }
        timer = Timer.scheduledTimer(withTimeInterval: 0.7, repeats: true) { [weak self] _ in self?.check() }
    }

    private func check() {
        let pb = NSPasteboard.general
        guard pb.changeCount != count else { return }
        count = pb.changeCount
        guard model.clipboardOn else { return }
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.secret) else { return }
        let app = NSWorkspace.shared.frontmostApplication?.localizedName ?? ""
        var clip: Clip?
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let names = urls.map(\.lastPathComponent)
            clip = Clip(text: names.count == 1 ? names[0] : "\(names.count) Dateien: " + names.joined(separator: ", "),
                        date: Date(), app: app, kind: .files(urls))
        } else if var text = pb.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            if text.count > 20_000 { text = String(text.prefix(20_000)) }
            clip = Clip(text: text, date: Date(), app: app)
        } else if let image = NSImage(pasteboard: pb), let tiff = image.tiffRepresentation,
                  let rep = NSBitmapImageRep(data: tiff), let png = rep.representation(using: .png, properties: [:]),
                  png.count < 12_000_000 {
            clip = Clip(text: "Bild \(rep.pixelsWide) × \(rep.pixelsHigh)", date: Date(), app: app, kind: .image(png))
        }
        guard let clip else { return }
        // Schon im Verlauf? Dann wandert der Eintrag nur nach oben.
        var clips = model.clips.filter { !($0.kind == clip.kind && $0.text == clip.text) }
        clips.insert(clip, at: 0)
        // Von den Bildern nur die neuesten behalten.
        var images = 0
        clips = clips.filter { c in
            if case .image = c.kind { images += 1; return images <= Self.imageLimit }
            return true
        }
        model.clips = Array(clips.prefix(Self.limit))
    }

    private func copy(_ clip: Clip) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch clip.kind {
        case .text: pb.setString(clip.text, forType: .string)
        case .image(let data): pb.setData(data, forType: .png)
        case .files(let urls): pb.writeObjects(urls as [NSURL])
        }
        count = pb.changeCount                      // die eigene Änderung nicht noch einmal aufnehmen
        var clips = model.clips.filter { $0.id != clip.id }
        var top = clip; top.date = Date()
        clips.insert(top, at: 0)
        model.clips = clips
    }
}
